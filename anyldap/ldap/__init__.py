"""python-ldap's ``ldap`` module, with every operation awaited.

The names, arguments and return values are the ones python-ldap documents::

    from anyldap import ldap

    async def example() -> None:
        async with ldap.initialize("ldap://ldap.example.com") as connection:
            await connection.simple_bind_s("cn=admin,dc=example,dc=com", "secret")
            for dn, attributes in await connection.search_s(
                "dc=example,dc=com", ldap.SCOPE_SUBTREE, "(cn=Babs*)"
            ):
                print(dn, attributes)

``ldap.controls``, ``ldap.schema``, ``ldap.sasl``, ``ldap.dn``,
``ldap.filter``, ``ldap.modlist`` and ``ldap.cidict`` are here too, and so
are the TLS options: setting ``OPT_X_TLS_CACERTFILE`` and its neighbours
builds the ``ssl.SSLContext`` the connection is raised with, and one can be
passed to ``initialize()`` instead.

SASL binds are made with the mechanisms in ``anyldap.ldap.sasl``, which
answer for themselves rather than through Cyrus SASL: EXTERNAL, PLAIN,
CRAM-MD5, DIGEST-MD5, and GSSAPI if the ``gssapi`` package is installed. A
mechanism of your own works if it answers ``process()`` the same way.

``ldap.asyncsearch`` reads a long search result by result,
``ldap.syncrepl`` keeps a copy of what a server holds, and
``ReconnectLDAPObject`` opens a connection again when the server goes away
and tries the operation once more.
"""

